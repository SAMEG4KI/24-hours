-- 24 HOURS database schema
-- Run this whole file in Supabase > SQL Editor.
create table if not exists public.responses (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  payload jsonb not null
);
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.responses enable row level security;
alter table public.admin_users enable row level security;

-- Public participants may submit anonymous survey data only.
drop policy if exists "Anyone can submit responses" on public.responses;
create policy "Anyone can submit responses"
on public.responses for insert
to anon, authenticated
with check (
  jsonb_typeof(payload) = 'object'
  and payload ? 'grade'
  and payload ? 'consent'
  and payload->>'consent' = 'true'
);

-- Only user IDs explicitly added to admin_users can read survey data.
drop policy if exists "Admins can read responses" on public.responses;
create policy "Admins can read responses"
on public.responses for select
to authenticated
using (
  exists (
    select 1 from public.admin_users a
    where a.user_id = auth.uid()
  )
);

-- Admin can verify their own allowlist membership. No public insert/update/delete.
drop policy if exists "Admins can read own access row" on public.admin_users;
create policy "Admins can read own access row"
on public.admin_users for select
to authenticated
using (user_id = auth.uid());

grant usage on schema public to anon, authenticated;
grant insert on public.responses to anon, authenticated;
grant select on public.responses to authenticated;
grant select on public.admin_users to authenticated;
grant usage, select on sequence public.responses_id_seq to anon, authenticated;

